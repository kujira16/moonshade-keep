  // 文字列 -> 0..4 の数値配列
  function parse(frame) {
    const w = Math.max(...frame.map((r) => r.length));
    const px = [];
    for (const row of frame) for (let x = 0; x < w; x++) {
      const c = row[x] || ".";
      px.push(c === "." ? 0 : +c);
    }
    return { w, h: frame.length, px };
  }

  // 数値データ -> canvas（通常 + 左右反転）
  function bake(f, pal) {
    const make = (flip) => {
      const c = document.createElement("canvas");
      c.width = f.w; c.height = f.h;
      const ctx = c.getContext("2d");
      const img = ctx.createImageData(f.w, f.h);
      for (let y = 0; y < f.h; y++) for (let x = 0; x < f.w; x++) {
        const v = f.px[y * f.w + (flip ? f.w - 1 - x : x)];
        if (!v) continue;
        const hex = pal[v - 1], i = (y * f.w + x) * 4;
        img.data[i] = parseInt(hex.slice(1, 3), 16);
        img.data[i + 1] = parseInt(hex.slice(3, 5), 16);
        img.data[i + 2] = parseInt(hex.slice(5, 7), 16);
        img.data[i + 3] = 255;
      }
      ctx.putImageData(img, 0, 0);
      return c;
    };
    return { w: f.w, h: f.h, img: make(false), flip: make(true) };
  }

  // PNG（AI生成画像など）を4階調に量子化して読み込む
  function quantizeImage(img, frameW) {
    const c = document.createElement("canvas");
    c.width = img.width; c.height = img.height;
    const ctx = c.getContext("2d");
    ctx.drawImage(img, 0, 0);
    const d = ctx.getImageData(0, 0, c.width, c.height).data;
    const fw = frameW || c.height, n = Math.max(1, Math.floor(c.width / fw)), frames = [];
    for (let k = 0; k < n; k++) {
      const px = [];
      for (let y = 0; y < c.height; y++) for (let x = 0; x < fw; x++) {
        const i = (y * c.width + k * fw + x) * 4;
        if (d[i + 3] < 128) { px.push(0); continue; }
        const lum = 0.299 * d[i] + 0.587 * d[i + 1] + 0.114 * d[i + 2];
        px.push(lum > 192 ? 1 : lum > 128 ? 2 : lum > 64 ? 3 : 4);
      }
      frames.push({ w: fw, h: c.height, px });
    }
    return frames;
  }

